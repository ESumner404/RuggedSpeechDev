// Writes website/board-data.js: the app's own starter words, folders and drawn
// symbols, so the "Have a go" board on the website is the real vocabulary and
// not a lookalike. Run it again whenever the starter words or symbols change:
//
//   node scripts/generate-website-board.mjs
//
// It uses esbuild, which is already installed as part of the build tools.
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const entry = `
import { STARTER_BOARDS, ROOT_BOARD_ID } from './src/renderer/vocab/starter';
import { HELP_ITEMS } from './src/renderer/vocab/feelingsHelp';
import { EMOJI_TO_SYMBOL, symbolDataUri } from './src/renderer/symbols/library';

const symbols = {};
const boards = {};
function pack(id, name, rows, columns, order, buttons, help) {
  const items = {};
  for (const it of buttons) {
    const char = it.image && it.image.kind === 'emoji' ? it.image.char : '';
    const sym = EMOJI_TO_SYMBOL[char];
    if (sym && !symbols[sym]) {
      const uri = symbolDataUri(sym);
      if (uri) symbols[sym] = uri;
    }
    items[it.id] = { l: it.label, c: it.background_color, e: char, s: sym && symbols[sym] ? sym : undefined, f: it.load_board ? it.load_board.id : undefined };
  }
  boards[id] = { n: name, g: [rows, columns], o: order, i: items, h: help ? 1 : undefined };
}
for (const b of STARTER_BOARDS) pack(b.id, b.name, b.grid.rows, b.grid.columns, b.grid.order, b.buttons, false);
const helpOrder = [];
for (let r = 0; r < 3; r += 1) helpOrder.push(HELP_ITEMS.slice(r * 3, r * 3 + 3).map((i) => i.id));
pack('help', 'Help', 3, 3, helpOrder, HELP_ITEMS, true);
globalThis.__out = JSON.stringify({ root: ROOT_BOARD_ID, boards, symbols });
`;

const result = await build({
  stdin: { contents: entry, resolveDir: root, sourcefile: 'entry.ts', loader: 'ts' },
  bundle: true,
  platform: 'node',
  format: 'cjs',
  write: false,
  logLevel: 'error',
});
const require = createRequire(import.meta.url);
const module = { exports: {} };
new Function('module', 'exports', 'require', result.outputFiles[0].text)(module, module.exports, require);
const data = globalThis.__out;
writeFileSync(
  join(root, 'website', 'board-data.js'),
  `// Generated by scripts/generate-website-board.mjs from the app's own starter vocabulary. Do not edit by hand.\nwindow.RS_BOARD = ${data};\n`,
);
const parsed = JSON.parse(data);
console.log(`Wrote website/board-data.js: ${Object.keys(parsed.boards).length} pages, ${Object.keys(parsed.symbols).length} drawn symbols, ${(data.length / 1024).toFixed(0)} KB.`);
