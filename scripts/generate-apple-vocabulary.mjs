// Writes apple/Shared/Vocabulary.swift: the app's own starter words, folders, feelings and help
// phrases, for the Apple Watch and Apple TV apps, so they say the same words in the same places
// and not a lookalike. Run it again whenever the starter words change:
//
//   npm run apple:vocabulary
//
// It uses esbuild, which is already installed as part of the build tools.
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const entry = `
import { STARTER_BOARDS, ROOT_BOARD_ID } from './src/renderer/vocab/starter';
import { FEELINGS_ITEMS, HELP_ITEMS, INTENSITIES } from './src/renderer/vocab/feelingsHelp';
import { QUICK_ACCESS_LABELS, QUICK_ACCESS_SPEECH } from './src/renderer/store/quickAccess';
import { FITZGERALD_COLORS } from './src/renderer/ui/fitzgerald';

const emoji = (it) => (it.image && it.image.kind === 'emoji' ? it.image.char : '');
const item = (it) => ({
  id: it.id,
  label: it.label,
  spoken: it.vocalization || it.label,
  emoji: emoji(it),
  colour: it.background_color || '',
  opens: it.load_board ? it.load_board.id : null,
});
globalThis.__out = JSON.stringify({
  root: ROOT_BOARD_ID,
  boards: STARTER_BOARDS.map((b) => ({
    id: b.id,
    name: b.name,
    rows: b.grid.rows,
    columns: b.grid.columns,
    order: b.grid.order,
    items: b.buttons.map(item),
  })),
  feelings: FEELINGS_ITEMS.map(item),
  help: HELP_ITEMS.map(item),
  intensities: INTENSITIES,
  quick: Object.entries(QUICK_ACCESS_SPEECH).map(([id, spoken]) => ({ id, label: QUICK_ACCESS_LABELS[id], spoken })),
  classes: FITZGERALD_COLORS,
});
`;

const result = await build({
  stdin: { contents: entry, resolveDir: root, sourcefile: 'entry.ts', loader: 'ts' },
  bundle: true,
  platform: 'node',
  format: 'cjs',
  write: false,
  logLevel: 'error',
});
const require = createRequire(import.meta.url);
const module = { exports: {} };
new Function('module', 'exports', 'require', result.outputFiles[0].text)(module, module.exports, require);
const data = JSON.parse(globalThis.__out);

const s = (text) => JSON.stringify(text); // a JSON string is also a valid Swift string
const hex = (colour) => (colour ? `0x${colour.replace('#', '').toUpperCase()}` : '0xFFFFFF');
const itemLine = (it) =>
  `VocabItem(id: ${s(it.id)}, label: ${s(it.label)}, spoken: ${s(it.spoken)}, emoji: ${s(it.emoji)}, colour: ${hex(it.colour)}, opens: ${it.opens ? s(it.opens) : 'nil'})`;
const orderLine = (row) => `[${row.map((cell) => (cell ? s(cell) : 'nil')).join(', ')}]`;

const lines = [];
lines.push('// Generated by scripts/generate-apple-vocabulary.mjs from the app\'s own starter vocabulary. Do not edit by hand.');
lines.push('// Run `npm run apple:vocabulary` after the starter words change.');
lines.push('');
lines.push('/// One button: what is written on it, what is spoken, its picture and its colour.');
lines.push('struct VocabItem: Identifiable, Hashable {');
lines.push('    let id: String');
lines.push('    let label: String');
lines.push('    let spoken: String');
lines.push('    let emoji: String');
lines.push('    /// The Fitzgerald Key colour, as 0xRRGGBB. Colour means the kind of word.');
lines.push('    let colour: UInt32');
lines.push('    /// The page this button opens, for a folder.');
lines.push('    let opens: String?');
lines.push('}');
lines.push('');
lines.push('/// A page of buttons in a fixed grid. `order` holds each place in the grid, with nil for an empty one.');
lines.push('struct VocabBoard: Identifiable {');
lines.push('    let id: String');
lines.push('    let name: String');
lines.push('    let rows: Int');
lines.push('    let columns: Int');
lines.push('    let order: [[String?]]');
lines.push('    let items: [VocabItem]');
lines.push('');
lines.push('    func item(_ id: String) -> VocabItem? { items.first { $0.id == id } }');
lines.push('}');
lines.push('');
lines.push('/// A button that speaks straight away, such as Yes or I need a break.');
lines.push('struct QuickPhrase: Identifiable, Hashable {');
lines.push('    let id: String');
lines.push('    let label: String');
lines.push('    let spoken: String');
lines.push('}');
lines.push('');
lines.push('enum Vocabulary {');
lines.push(`    static let rootID = ${s(data.root)}`);
lines.push('');
lines.push('    static let boards: [VocabBoard] = [');
for (const b of data.boards) {
  lines.push('        VocabBoard(');
  lines.push(`            id: ${s(b.id)}, name: ${s(b.name)}, rows: ${b.rows}, columns: ${b.columns},`);
  lines.push(`            order: [${b.order.map(orderLine).join(', ')}],`);
  lines.push('            items: [');
  for (const it of b.items) lines.push(`                ${itemLine(it)},`);
  lines.push('            ]');
  lines.push('        ),');
}
lines.push('    ]');
lines.push('');
lines.push('    static func board(_ id: String) -> VocabBoard? { boards.first { $0.id == id } }');
lines.push('    static var root: VocabBoard { board(rootID)! }');
lines.push('');
lines.push('    static let feelings: [VocabItem] = [');
for (const it of data.feelings) lines.push(`        ${itemLine(it)},`);
lines.push('    ]');
lines.push('');
lines.push(`    static let intensities: [String] = [${data.intensities.map(s).join(', ')}]`);
lines.push('');
lines.push('    /// Spoken and then nothing more: the app is not a safeguarding record, and these are never logged differently.');
lines.push('    static let help: [VocabItem] = [');
for (const it of data.help) lines.push(`        ${itemLine(it)},`);
lines.push('    ]');
lines.push('');
lines.push('    static let quick: [QuickPhrase] = [');
for (const q of data.quick) lines.push(`        QuickPhrase(id: ${s(q.id)}, label: ${s(q.label)}, spoken: ${s(q.spoken)}),`);
lines.push('    ]');
lines.push('');
lines.push('    static func quickPhrase(_ id: String) -> QuickPhrase? { quick.first { $0.id == id } }');
lines.push('');
lines.push('    /// Said when someone presses Give me time.');
lines.push(`    static let giveMeTime = ${s('I know what I want to say. Please give me a moment.')}`);
lines.push('}');
lines.push('');
writeFileSync(join(root, 'apple', 'Shared', 'Vocabulary.swift'), lines.join('\n'));
console.log(`Wrote apple/Shared/Vocabulary.swift: ${data.boards.length} pages, ${data.feelings.length} feelings, ${data.help.length} help phrases.`);
